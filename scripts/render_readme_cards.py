def svg(width,height,body,label,bottom=12,left=0,right=0):
    if left:
        body=f'<g transform="translate({left} 0)">{body}</g>'
    width += left + right
    css=CSS
    if os.getenv("STATIC"):
        css += ".r,.f,.g,.p,.live,.ti{animation:none!important;opacity:1!important;transform:none!important}.sh{display:none}"
    height += bottom
    return f'<svg xmlns="http://www.w3.org/2000/svg" width="{width}" height="{height}" viewBox="0 0 {width} {height}" role="img" aria-label="{escape(label)}"><title>{escape(label)}</title><style>{css}</style>{body}</svg>'

def write(name,content):
    (OUT/name).write_text(content,encoding="utf-8")
    print(f"wrote cards/{name}")

def delay(seconds):
    return f'style="animation-delay:{seconds:.2f}s"'

def wrap(text,limit):
    rows=[]; row=""
    for word in text.split():
        if row and len(row)+len(word)+1>limit:
            rows.append(row); row=word
        else: row=f"{row} {word}".strip()
    return rows+[row] if row else []

def lines_svg(x,y,rows,line_height,attrs):
    return "".join(f'<text x="{x}" y="{y+i*line_height}" {attrs}>{escape(row)}</text>' for i,row in enumerate(rows))

def ascii_portrait():
    """Embed the detailed ASCII rows generated by the portrait pipeline."""
    source = ROOT/"assets/aymane-ascii.svg"
    if not source.exists():
        raise FileNotFoundError("Run prep_photo.py and make_ascii_svg.py first.")
    source_svg = source.read_text(encoding="utf-8")
    rows = re.findall(r'<text xml:space="preserve"[^>]*\by="([\d.]+)"[^>]*>(.*?)</text>', source_svg, re.S)
    # The source avatar has dark artwork at its far left/right edges; trim those
    # margins so they do not become two distracting vertical ASCII bars.
    return "".join(
        f'<text class="f" style="animation-delay:{.18+i*.012:.3f}s" x="0" y="{float(y)+10:.2f}" font-family="{MONO}" font-size="5.8" textLength="320" lengthAdjust="spacing" xml:space="preserve" fill="{RED}">{row[11:-11]}</text>'
        for i, (y, row) in enumerate(rows)
    )

