def repo_stars():
    result={}
    for name,*_ in REPOS:
        try:
            response=requests.get(f"https://api.github.com/repos/{USER}/{name}",timeout=12)
            if response.ok: result[name]=response.json().get("stargazers_count",0)
        except requests.RequestException:
            pass
    return result

